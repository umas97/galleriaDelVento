"""Write ``frontend/src/sim2d/lattice.generated.ts`` from ``gdv/lattice.py`` (SPEC §10.2).

    uv run python scripts/gen_lattice_ts.py           # write the file
    uv run python scripts/gen_lattice_ts.py --check   # exit 1 if it is stale

Numbers are written with ``repr``: the shortest text that reads back as the
same double, in Python and in JavaScript alike.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from gdv import lattice  # noqa: E402

TARGET = ROOT / "frontend" / "src" / "sim2d" / "lattice.generated.ts"


def _list(values) -> str:
    return "[" + ", ".join(repr(v) for v in values) + "]"


def flat(array) -> str:
    return _list(float(v) for v in array.ravel())


def ints(array) -> str:
    return _list(int(v) for v in array.ravel())


def render() -> str:
    lines = [
        "// galleriaDelVento -- real-time 2D wind tunnel for sections, sketches and profiles",
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "//",
        "// GENERATED by scripts/gen_lattice_ts.py from backend/gdv/lattice.py: do not edit.",
        "// Test 20 fails when this file and the Python module disagree.",
        "",
        f"export const Q = {lattice.Q}",
        "/** Velocities, interleaved (cx, cy) per direction. */",
        f"export const C = {ints(lattice.C)} as const",
        f"export const W = {flat(lattice.W)} as const",
        f"export const OPPOSITE = {ints(lattice.OPPOSITE)} as const",
        f"export const MIRROR_Y = {ints(lattice.MIRROR_Y)} as const",
        "/** Moment matrix, row-major 9x9. */",
        f"export const M = {flat(lattice.M)} as const",
        "/** Its inverse, row-major 9x9. */",
        f"export const MINV = {flat(lattice.MINV)} as const",
        f"export const S_E = {lattice.S_E!r}",
        f"export const S_EPS = {lattice.S_EPS!r}",
        f"export const S_Q = {lattice.S_Q!r}",
        f"export const CS_SMAGORINSKY = {lattice.CS_SMAGORINSKY!r}",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            print(f"{TARGET} non corrisponde a gdv/lattice.py: rigeneralo", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"scritto {TARGET}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
