"""Write the lattice constants for the interface from their Python source.

- ``frontend/src/sim2d/lattice.generated.ts`` from ``gdv/lattice.py`` (D2Q9,
  SPEC §10.2, test 20);
- ``frontend/src/sim3d/lattice3d.generated.ts`` from ``gdv/lattice3d.py``
  (D3Q19, SPEC §24.3, test 35).

    uv run python scripts/gen_lattice_ts.py           # write the files
    uv run python scripts/gen_lattice_ts.py --check   # exit 1 if one is stale

Numbers are written with ``repr``: the shortest text that reads back as the
same double, in Python and in JavaScript alike.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from gdv import lattice, lattice3d  # noqa: E402

TARGET = ROOT / "frontend" / "src" / "sim2d" / "lattice.generated.ts"
TARGET_3D = ROOT / "frontend" / "src" / "sim3d" / "lattice3d.generated.ts"


def _list(values) -> str:
    return "[" + ", ".join(repr(v) for v in values) + "]"


def flat(array) -> str:
    return _list(float(v) for v in array.ravel())


def ints(array) -> str:
    return _list(int(v) for v in array.ravel())


def render() -> str:
    lines = [
        "// galleriaDelVento -- real-time 2D wind tunnel for sections, sketches and profiles",
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "//",
        "// GENERATED by scripts/gen_lattice_ts.py from backend/gdv/lattice.py: do not edit.",
        "// Test 20 fails when this file and the Python module disagree.",
        "",
        f"export const Q = {lattice.Q}",
        "/** Velocities, interleaved (cx, cy) per direction. */",
        f"export const C = {ints(lattice.C)} as const",
        f"export const W = {flat(lattice.W)} as const",
        f"export const OPPOSITE = {ints(lattice.OPPOSITE)} as const",
        f"export const MIRROR_Y = {ints(lattice.MIRROR_Y)} as const",
        "/** Moment matrix, row-major 9x9. */",
        f"export const M = {flat(lattice.M)} as const",
        "/** Its inverse, row-major 9x9. */",
        f"export const MINV = {flat(lattice.MINV)} as const",
        f"export const S_E = {lattice.S_E!r}",
        f"export const S_EPS = {lattice.S_EPS!r}",
        f"export const S_Q = {lattice.S_Q!r}",
        f"export const CS_SMAGORINSKY = {lattice.CS_SMAGORINSKY!r}",
        "",
    ]
    return "\n".join(lines)


def render_3d() -> str:
    lines = [
        "// galleriaDelVento -- real-time 2D wind tunnel for sections, sketches and profiles",
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "//",
        "// GENERATED by scripts/gen_lattice_ts.py from backend/gdv/lattice3d.py: do not edit.",
        "// Test 35 fails when this file and the Python module disagree.",
        "",
        f"export const Q = {lattice3d.Q}",
        "/** Velocities, interleaved (cx, cy, cz) per direction. */",
        f"export const C = {ints(lattice3d.C)} as const",
        f"export const W = {flat(lattice3d.W)} as const",
        f"export const OPPOSITE = {ints(lattice3d.OPPOSITE)} as const",
        "/** Free slip: [k * 4 + flags], cy flipped if flags & 1, cz if flags & 2. */",
        f"export const MIRROR = {ints(lattice3d.MIRROR)} as const",
        "/** Moment matrix, row-major 19x19. */",
        f"export const M = {flat(lattice3d.M)} as const",
        "/** Its inverse, row-major 19x19. */",
        f"export const MINV = {flat(lattice3d.MINV)} as const",
        "/** Moments of the rest state, M · W. */",
        f"export const REST_MOMENTS = {flat(lattice3d.REST_MOMENTS)} as const",
        f"export const S_E = {lattice3d.S_E!r}",
        f"export const S_EPS = {lattice3d.S_EPS!r}",
        f"export const S_Q = {lattice3d.S_Q!r}",
        f"export const S_PI = {lattice3d.S_PI!r}",
        f"export const S_M = {lattice3d.S_M!r}",
        f"export const CS_SMAGORINSKY = {lattice3d.CS_SMAGORINSKY!r}",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    outputs = [(TARGET, render(), "gdv/lattice.py"), (TARGET_3D, render_3d(), "gdv/lattice3d.py")]
    if "--check" in argv:
        stale = False
        for target, text, source in outputs:
            current = target.read_text(encoding="utf-8") if target.exists() else ""
            if current != text:
                print(f"{target} non corrisponde a {source}: rigeneralo", file=sys.stderr)
                stale = True
        return 1 if stale else 0
    for target, text, _ in outputs:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
        print(f"scritto {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
